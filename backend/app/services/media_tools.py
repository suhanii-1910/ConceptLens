import json
import logging
import os
import subprocess
from typing import Any, Dict, List

logger = logging.getLogger(__name__)


class MediaProbeError(Exception):
    pass


class MediaTools:
    def __init__(self, timeout_seconds: int = 300):
        self.timeout_seconds = timeout_seconds

    def probe_media(self, file_path: str) -> Dict[str, Any]:
        """Probe media container/streams using ffprobe."""
        cmd = [
            "ffprobe",
            "-v", "error",
            "-show_format",
            "-show_streams",
            "-of", "json",
            file_path,
        ]
        try:
            result = subprocess.run(
                cmd,
                capture_output=True,
                text=True,
                timeout=self.timeout_seconds,
            )
            if result.returncode != 0:
                raise MediaProbeError(f"ffprobe failed: {result.stderr}")
            return json.loads(result.stdout)
        except subprocess.TimeoutExpired as exc:
            raise MediaProbeError("ffprobe timed out") from exc
        except FileNotFoundError as exc:
            raise MediaProbeError("ffprobe executable not found") from exc
        except json.JSONDecodeError as exc:
            raise MediaProbeError("ffprobe returned invalid JSON") from exc

    def probe_video_frames(self, file_path: str) -> List[Dict[str, Any]]:
        """
        Return actual decoded video-frame metadata from ffprobe.

        Timestamps come from ffprobe's decoded-frame timing. They are not
        mathematically generated by ConceptLens.
        """
        cmd = [
            "ffprobe",
            "-v", "error",
            "-select_streams", "v:0",
            "-show_frames",
            "-show_entries",
            "frame=best_effort_timestamp_time,pts_time,key_frame,width,height",
            "-of", "json",
            file_path,
        ]

        try:
            result = subprocess.run(
                cmd,
                capture_output=True,
                text=True,
                timeout=self.timeout_seconds,
            )
            if result.returncode != 0:
                raise MediaProbeError(
                    f"ffprobe frame probing failed: {result.stderr}"
                )

            payload = json.loads(result.stdout)

        except subprocess.TimeoutExpired as exc:
            raise MediaProbeError("ffprobe frame probing timed out") from exc
        except FileNotFoundError as exc:
            raise MediaProbeError("ffprobe executable not found") from exc
        except json.JSONDecodeError as exc:
            raise MediaProbeError(
                "ffprobe frame probing returned invalid JSON"
            ) from exc

        frames: List[Dict[str, Any]] = []

        for frame_index, frame in enumerate(payload.get("frames", [])):
            raw_timestamp = frame.get("best_effort_timestamp_time")
            timestamp_source = "ffprobe_best_effort_timestamp_time"

            if raw_timestamp in (None, "N/A"):
                raw_timestamp = frame.get("pts_time")
                timestamp_source = "ffprobe_pts_time"

            if raw_timestamp in (None, "N/A"):
                continue

            try:
                timestamp_seconds = float(raw_timestamp)
            except (TypeError, ValueError):
                continue

            width = frame.get("width")
            height = frame.get("height")

            frames.append(
                {
                    "frame_index": frame_index,
                    "timestamp_seconds": timestamp_seconds,
                    "timestamp_source": timestamp_source,
                    "key_frame": bool(int(frame.get("key_frame", 0))),
                    "width": int(width) if width is not None else None,
                    "height": int(height) if height is not None else None,
                }
            )

        return frames

    def extract_audio(self, video_path: str, output_path: str) -> None:
        """Extract 16 kHz mono PCM audio for transcription."""
        cmd = [
            "ffmpeg",
            "-i", video_path,
            "-vn",
            "-acodec", "pcm_s16le",
            "-ac", "1",
            "-ar", "16000",
            "-y",
            output_path,
        ]
        try:
            result = subprocess.run(
                cmd,
                capture_output=True,
                text=True,
                timeout=self.timeout_seconds,
            )
            if result.returncode != 0:
                raise MediaProbeError(
                    f"ffmpeg audio extraction failed: {result.stderr}"
                )
        except subprocess.TimeoutExpired as exc:
            raise MediaProbeError("ffmpeg audio extraction timed out") from exc
        except FileNotFoundError as exc:
            raise MediaProbeError("ffmpeg executable not found") from exc

    def extract_frame_by_index(
        self,
        video_path: str,
        frame_index: int,
        output_path: str,
    ) -> None:
        """
        Extract the exact decoded frame selected from ffprobe metadata.

        Frame selection uses the decoded frame index instead of seeking to a
        synthetic timestamp.
        """
        if frame_index < 0:
            raise MediaProbeError(
                f"Invalid decoded frame index: {frame_index}"
            )

        select_expression = f"select=eq(n\\,{frame_index})"

        cmd = [
            "ffmpeg",
            "-v", "error",
            "-i", video_path,
            "-vf", select_expression,
            "-frames:v", "1",
            "-q:v", "2",
            "-y",
            output_path,
        ]

        try:
            result = subprocess.run(
                cmd,
                capture_output=True,
                text=True,
                timeout=self.timeout_seconds,
            )
            if result.returncode != 0:
                raise MediaProbeError(
                    f"ffmpeg frame extraction failed: {result.stderr}"
                )

            if not os.path.exists(output_path) or os.path.getsize(output_path) == 0:
                raise MediaProbeError(
                    f"ffmpeg produced no frame for decoded index {frame_index}"
                )

        except subprocess.TimeoutExpired as exc:
            raise MediaProbeError("ffmpeg frame extraction timed out") from exc
        except FileNotFoundError as exc:
            raise MediaProbeError("ffmpeg executable not found") from exc

    def extract_frame_at_time(
        self,
        video_path: str,
        timestamp: float,
        output_path: str,
    ) -> None:
        """
        Legacy utility retained for compatibility.

        Phase 1C evidence generation does not use this method because citation
        timestamps must come from actual decoded-frame metadata.
        """
        cmd = [
            "ffmpeg",
            "-ss", str(timestamp),
            "-i", video_path,
            "-frames:v", "1",
            "-q:v", "2",
            "-y",
            output_path,
        ]
        try:
            result = subprocess.run(
                cmd,
                capture_output=True,
                text=True,
                timeout=self.timeout_seconds,
            )
            if result.returncode != 0:
                raise MediaProbeError(
                    f"ffmpeg frame extraction failed: {result.stderr}"
                )
        except subprocess.TimeoutExpired as exc:
            raise MediaProbeError("ffmpeg frame extraction timed out") from exc
        except FileNotFoundError as exc:
            raise MediaProbeError("ffmpeg executable not found") from exc
