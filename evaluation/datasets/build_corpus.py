    offset = 0.0
    clips = []
    for i, script in enumerate(segments):
        audio, clip = Path(tmp) / f"part{i}.aiff", Path(tmp) / f"part{i}.mp4"
        run(["say", "-r", "155", "-o", str(audio), script])
        run(["ffmpeg", "-y", "-f", "lavfi", "-i", "color=c=0x172235:s=640x360:r=10", "-i", str(audio),
             "-shortest", "-c:v", "libx264", "-pix_fmt", "yuv420p", "-c:a", "aac", str(clip)])
        duration = float(run(["ffprobe", "-v", "error", "-show_entries", "format=duration", "-of", "default=nw=1:nk=1", str(clip)]))
        intervals.append({"start": round(offset, 3), "end": round(offset + duration, 3), "transcript": script})
        offset += duration
        clips.append(clip)
    listing = Path(tmp) / "list.txt"
    listing.write_text("\n".join(f"file '{p}'" for p in clips))
    run(["ffmpeg", "-y", "-f", "concat", "-safe", "0", "-i", str(listing), "-c", "copy", str(OUT / "aster-demonstration.mp4")])
